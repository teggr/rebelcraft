package io.github.teggr.rebelcraft.showcase;

import io.github.teggr.html.preview.Preview;
import j2html.tags.DomContent;

import static j2html.TagCreator.*;

public class ShowcasePages {
    public DomContent repositoryExplorerPage() {
        return explorerPage(
                "GitHub repository explorer | RebelCraft",
                "../",
                "../showcase.css",
                "../repository-explorer.js"
        );
    }

    public DomContent landingPage() {
        return explorerPage(
                "RebelCraft Java HTML Showcase",
                "./",
                "showcase.css",
                "repository-explorer.js"
        );
    }

    private DomContent explorerPage(String title, String homePath, String stylesheet, String scriptPath) {
        return ShowcaseLayout.page(
                title,
                div().withClasses("explorer-page").with(
                        div().withClasses("hero-copy").with(
                                span("The RebelCraft Java HTML showcase").withClasses("eyebrow"),
                                h1("Build web experiences in Java."),
                                p("Explore reusable j2html components, TeaVM-compiled browser code, and Electrostatic publishing in one working showcase."),
                                a("Browse the component catalog")
                                        .withClasses("button-link")
                                        .withHref(homePath + "catalog/")
                        ),
                        RepositoryExplorer.create(),
                        section().withClasses("ecosystem-strip").with(
                                h2("The tools behind this page"),
                                div().withClasses("project-grid").with(
                                        ProjectCard.create(
                                                "j2html",
                                                "Generate type-safe HTML from Java without writing template strings.",
                                                "https://github.com/tipsy/j2html",
                                                "1.6.0"
                                        ),
                                        ProjectCard.create(
                                                "j2html-toolkit",
                                                "Reusable Java components and extensions for building HTML.",
                                                "https://github.com/teggr/j2html-toolkit",
                                                "0.0.6"
                                        ),
                                        ProjectCard.create(
                                                "java-html-toolkit",
                                                "Preview and catalog HTML generated by Java components.",
                                                "https://github.com/teggr/java-html-toolkit",
                                                "1.0.3"
                                        ),
                                        ProjectCard.create(
                                                "Electrostatic",
                                                "Publish project documentation as a generated static site.",
                                                "https://github.com/teggr/electrostatic",
                                                "0.0.4"
                                        ),
                                        ProjectCard.create(
                                                "TeaVM",
                                                "Compile Java to JavaScript for client-side browser behavior.",
                                                "https://teavm.org/docs/intro/getting-started.html",
                                                "0.16.0"
                                        )
                                )
                        )
                ),
                stylesheet,
                scriptPath,
                homePath
        );
    }

    @Preview(value = "Repository explorer controls", group = "RebelCraft")
    public String repositoryExplorerControls() {
        return RepositoryExplorer.create().render();
    }

    @Preview(value = "Project card", group = "RebelCraft")
    public String projectCard() {
        return ProjectCard.create(
                "j2html-toolkit",
                "Reusable Java components and extensions for building HTML.",
                "https://github.com/teggr/j2html-toolkit",
                "0.0.6"
        ).render();
    }

    @Preview(value = "Explorer page layout", group = "RebelCraft")
    public String pageLayout() {
        return ShowcaseLayout.page(
                "Component preview",
                RepositoryExplorer.create(),
                null,
                null
        ).render();
    }
}
